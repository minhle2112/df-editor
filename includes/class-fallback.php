<?php
/**
 * Plain-text fallback for post_content: headings, texts and links of a layout, so a DF page
 * stays readable (and searchable) when DF Editor is switched off.
 *
 * Never used for layouts with a "seiteninhalt" section: there post_content is real content.
 *
 * @package DF_Editor
 */

defined( 'ABSPATH' ) || exit;

final class DF_Fallback {

	/** Marker at the start of generated content; only marked (or empty) content is replaced. */
	public const MARKER = '<!-- df-editor:fallback -->';

	/** Text fields printed as headings. */
	private const HEADING_FIELDS = array( 'title', 'headline', 'heading', 'question', 'name' );

	/** Text fields that are decoration only. */
	private const SKIP_FIELDS = array( 'eyebrow' );

	/**
	 * Whether the layout keeps real post_content (seiteninhalt).
	 */
	public static function applies( array $layout ): bool {
		return ! DF_Layout_Store::has_section_type( $layout, 'seiteninhalt' );
	}

	/**
	 * Whether post_content may be replaced (empty or generated by us).
	 */
	public static function can_replace( string $content ): bool {
		return '' === trim( $content ) || 0 === strpos( ltrim( $content ), self::MARKER );
	}

	/**
	 * Builds the fallback HTML (plain <h2>/<p>, rendered as a Classic block by the editor).
	 */
	public static function build( array $layout, string $page_key ): string {
		$out = array( self::MARKER );
		foreach ( (array) ( $layout['sections'] ?? array() ) as $inst ) {
			if ( ! is_array( $inst ) || ! empty( $inst['hidden'] ) ) {
				continue;
			}
			$def = DF_Registry::get( (string) ( $inst['section'] ?? '' ) );
			if ( null === $def || ! preg_match( DF_Layout_Store::INSTANCE_REGEX, (string) ( $inst['id'] ?? '' ) ) ) {
				continue;
			}
			$s     = new DF_Section( $inst, $def, $page_key );
			$level = in_array( $s->opt( 'heading_level' ), array( 'h1', 'h2', 'h3' ), true ) ? $s->opt( 'heading_level' ) : 'h2';
			$out   = array_merge( $out, self::fields( $s, (array) $def['fields'], $level ) );

			// source=cpt: the list comes from posts, the manual defaults are placeholders.
			if ( 'cpt' === $s->opt( 'source' ) ) {
				continue;
			}
			$sub = 'h1' === $level ? 'h2' : 'h3';
			foreach ( $s->items() as $item ) {
				$out = array_merge( $out, self::fields( $item, (array) ( $def['list']['fields'] ?? array() ), $sub ) );
			}
		}
		return implode( "\n\n", array_filter( $out ) );
	}

	/**
	 * @param DF_Field_Scope $scope  Section or list item.
	 * @param array          $fields Field definitions.
	 * @param string         $level  Heading tag for heading fields.
	 * @return string[]
	 */
	private static function fields( DF_Field_Scope $scope, array $fields, string $level ): array {
		$out = array();
		foreach ( $fields as $name => $field ) {
			$type = (string) ( $field['type'] ?? 'text' );
			if ( in_array( $name, self::SKIP_FIELDS, true ) || in_array( $type, array( 'image', 'setting' ), true ) ) {
				continue;
			}
			$value = $scope->value( (string) $name );
			if ( 'button' === $type ) {
				$text = is_array( $value ) ? trim( (string) ( $value['text'] ?? '' ) ) : '';
				$url  = is_array( $value ) ? (string) ( $value['url'] ?? '' ) : '';
				if ( '' !== $text && '' !== $url && '#' !== $url ) {
					$out[] = sprintf( '<p><a href="%s">%s</a></p>', esc_url( $url ), esc_html( $text ) );
				}
				continue;
			}
			$value = is_scalar( $value ) ? trim( (string) $value ) : '';
			if ( '' === $value ) {
				continue;
			}
			if ( 'richtext' === $type ) {
				$out[] = trim( wp_kses( $value, DF_Content::richtext_tags() ) );
			} elseif ( in_array( $name, self::HEADING_FIELDS, true ) || str_ends_with( (string) $name, '_title' ) ) {
				$out[] = sprintf( '<%1$s>%2$s</%1$s>', $level, esc_html( $value ) );
			} else {
				$out[] = '<p>' . esc_html( $value ) . '</p>';
			}
		}
		return $out;
	}

	/**
	 * Writes the fallback into post_content when allowed.
	 *
	 * Never writes while a visible section has no registered type (e.g. a removed library
	 * section): build() would skip it and replace the existing text with an empty fallback.
	 *
	 * @return string "written", "skipped-seiteninhalt", "skipped-content",
	 *                "skipped-missing-sections" or "error".
	 */
	public static function write( int $post_id, bool $overwrite = false ): string {
		$layout = DF_Layout_Store::get( $post_id );
		if ( null === $layout || ! self::applies( $layout ) ) {
			return 'skipped-seiteninhalt';
		}
		$current = (string) get_post_field( 'post_content', $post_id );
		if ( ! $overwrite && ! self::can_replace( $current ) ) {
			return 'skipped-content';
		}
		if ( self::has_missing_sections( $layout ) ) {
			return 'skipped-missing-sections';
		}
		$html = self::build( $layout, (string) $layout['page_key'] );
		if ( trim( $html ) === trim( $current ) ) {
			return 'written';
		}
		$result = wp_update_post(
			array(
				'ID'           => $post_id,
				'post_content' => wp_slash( $html ),
			),
			true
		);
		return is_wp_error( $result ) ? 'error' : 'written';
	}

	/**
	 * Whether a visible layout entry uses a section type that is not registered.
	 */
	public static function has_missing_sections( array $layout ): bool {
		foreach ( (array) ( $layout['sections'] ?? array() ) as $inst ) {
			if ( ! is_array( $inst ) || ! empty( $inst['hidden'] ) ) {
				continue;
			}
			if ( null === DF_Registry::get( (string) ( $inst['section'] ?? '' ) ) ) {
				return true;
			}
		}
		return false;
	}
}
