<?php
/**
 * Field ID guard (no WordPress needed).
 *
 * Compares the field IDs of every sections/<type>/section.json (fields + list fields) with
 * field-ids.lock.json. Published field IDs must never be removed, renamed or change type,
 * otherwise client content is orphaned (see docs/CONVENTIONS.md §3).
 *
 * Usage:
 *   php bin/check-field-ids.php            check, exit 1 on a breaking change
 *   php bin/check-field-ids.php --update   rewrite the lock from the current section.json files
 *                                          (refuses removals/type changes unless --allow-break)
 *   php bin/check-field-ids.php --against=<lock file>
 *                                          check against another lock, e.g. the previous release
 *                                          tag's field-ids.lock.json (used by release.yml)
 *
 * Lock format: { "sections": { "<type>": { "<field id>": "<type>", "items.{n}.<sub>": "<type>" } } }
 *
 * @package DF_Editor
 */

if ( PHP_SAPI !== 'cli' ) {
	exit( 1 );
}

$root   = dirname( __DIR__ );
$lock   = $root . '/field-ids.lock.json';
$cli    = array_slice( $argv, 1 );
$update = in_array( '--update', $cli, true );
$allow  = in_array( '--allow-break', $cli, true );
foreach ( $cli as $arg ) {
	if ( 0 === strpos( $arg, '--against=' ) ) {
		$lock = substr( $arg, 10 );
		if ( $update || ! is_readable( $lock ) ) {
			fwrite( STDERR, "ERROR  --against needs a readable lock file and cannot be combined with --update.\n" );
			exit( 1 );
		}
	}
}

/**
 * Collects field IDs => type of all plugin sections.
 *
 * @return array{0:array<string,array<string,string>>,1:string[]} [ sections, errors ]
 */
function df_collect_field_ids( string $root ): array {
	$sections = array();
	$errors   = array();
	$files    = glob( $root . '/sections/*/section.json' ) ?: array();
	sort( $files, SORT_STRING );
	foreach ( $files as $file ) {
		$rel = substr( $file, strlen( $root ) + 1 );
		$def = json_decode( (string) file_get_contents( $file ), true );
		if ( ! is_array( $def ) || empty( $def['type'] ) ) {
			$errors[] = "$rel: invalid JSON or missing \"type\" (" . json_last_error_msg() . ')';
			continue;
		}
		$type = (string) $def['type'];
		if ( basename( dirname( $file ) ) !== $type ) {
			$errors[] = "$rel: \"type\" ($type) must equal the folder name.";
		}
		$ids = array();
		foreach ( (array) ( $def['fields'] ?? array() ) as $name => $field ) {
			$ids[ (string) $name ] = (string) ( $field['type'] ?? 'text' );
		}
		if ( ! empty( $def['list'] ) && is_array( $def['list'] ) ) {
			$key = (string) ( $def['list']['key'] ?? 'items' );
			foreach ( (array) ( $def['list']['fields'] ?? array() ) as $name => $field ) {
				$ids[ $key . '.{n}.' . $name ] = (string) ( $field['type'] ?? 'text' );
			}
		}
		foreach ( array_keys( $ids ) as $id ) {
			if ( ! preg_match( '/^[a-z0-9][a-z0-9_{}.-]*$/', $id ) ) {
				$errors[] = "$rel: field \"$id\" uses characters outside [a-z0-9_-].";
			}
		}
		ksort( $ids, SORT_STRING );
		$sections[ $type ] = $ids;
	}
	ksort( $sections, SORT_STRING );
	return array( $sections, $errors );
}

[ $current, $errors ] = df_collect_field_ids( $root );

foreach ( $errors as $error ) {
	fwrite( STDERR, "ERROR  $error\n" );
}

$locked = array();
if ( is_readable( $lock ) ) {
	$data = json_decode( (string) file_get_contents( $lock ), true );
	if ( ! is_array( $data ) || ! isset( $data['sections'] ) || ! is_array( $data['sections'] ) ) {
		fwrite( STDERR, "ERROR  field-ids.lock.json is not valid.\n" );
		exit( 1 );
	}
	$locked = $data['sections'];
} elseif ( ! $update ) {
	fwrite( STDERR, "ERROR  field-ids.lock.json missing. Run: php bin/check-field-ids.php --update\n" );
	exit( 1 );
}

$breaking = array();
$added    = array();
foreach ( $locked as $type => $ids ) {
	if ( ! isset( $current[ $type ] ) ) {
		$breaking[] = "section \"$type\" was removed (its content would be orphaned)";
		continue;
	}
	foreach ( (array) $ids as $id => $field_type ) {
		if ( ! isset( $current[ $type ][ $id ] ) ) {
			$breaking[] = "$type: field \"$id\" was removed or renamed";
		} elseif ( $current[ $type ][ $id ] !== $field_type ) {
			$breaking[] = "$type: field \"$id\" changed type $field_type -> {$current[ $type ][ $id ]}";
		}
	}
}
foreach ( $current as $type => $ids ) {
	foreach ( $ids as $id => $field_type ) {
		if ( ! isset( $locked[ $type ][ $id ] ) ) {
			$added[] = "$type: $id ($field_type)";
		}
	}
}

if ( $update ) {
	if ( $breaking && ! $allow ) {
		foreach ( $breaking as $msg ) {
			fwrite( STDERR, "BREAK  $msg\n" );
		}
		fwrite( STDERR, "\nLock NOT updated: published field IDs must not be removed, renamed or change type.\nOnly for a deliberate major release (legacy_ids / migration): --update --allow-break\n" );
		exit( 1 );
	}
	foreach ( $breaking as $msg ) {
		fwrite( STDERR, "WARN   $msg (lock updated, --allow-break)\n" );
	}
	$json = json_encode(
		array(
			'_comment' => 'Published DF Editor field IDs. Generated by bin/check-field-ids.php --update. Never remove entries by hand.',
			'sections' => $current,
		),
		JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE
	);
	$json = preg_replace_callback( '/^(?: {4})+/m', static fn( $m ) => str_repeat( "\t", (int) ( strlen( $m[0] ) / 4 ) ), (string) $json );
	file_put_contents( $lock, $json . "\n" );
	$count = array_sum( array_map( 'count', $current ) );
	echo 'Lock written: ' . count( $current ) . " sections, $count field IDs.\n";
	exit( $errors ? 1 : 0 );
}

foreach ( $added as $msg ) {
	echo "NEW    $msg\n";
}
foreach ( $breaking as $msg ) {
	fwrite( STDERR, "BREAK  $msg\n" );
}

if ( $breaking || $errors ) {
	fwrite( STDERR, "\nField ID check failed. Published field IDs must not be removed, renamed or change type.\n" );
	exit( 1 );
}
if ( $added ) {
	echo "\nOK, with new field IDs. Run with --update to lock them.\n";
} else {
	echo "OK: all locked field IDs present.\n";
}
exit( 0 );
